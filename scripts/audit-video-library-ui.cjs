// After build: electron scripts/audit-video-library-ui.cjs <20-second MP4 fixture>
const { app, BrowserWindow, ipcMain, protocol } = require('electron')
const { mkdirSync } = require('node:fs')
const { copyFile, mkdir, readFile, writeFile, access } = require('node:fs/promises')
const { resolve, join } = require('node:path')
const { randomUUID } = require('node:crypto')
const assert = require('node:assert/strict')
const ts = require('typescript')

const output = resolve(__dirname, '../out/audit-video-library-ui')
mkdirSync(join(output, 'user-data'), { recursive: true })
app.setPath('userData', join(output, 'user-data'))
app.setPath('sessionData', join(output, 'user-data'))
protocol.registerSchemesAsPrivileged([{ scheme: 'gacha-video', privileges: { standard: true, secure: true, stream: true } }])
const pause = (ms) => new Promise((resolve) => setTimeout(resolve, ms))
async function until(window, expression) {
  for (let index = 0; index < 160; index += 1) {
    const value = await window.webContents.executeJavaScript(expression)
    if (value) return value
    await pause(50)
  }
  throw new Error(`Timed out: ${expression}`)
}
async function capture(window, name) {
  await window.webContents.executeJavaScript('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))')
  await pause(150)
  await writeFile(join(output, name), (await window.webContents.capturePage()).toPNG())
}
async function run() {
  if (!process.argv[2]) throw new Error('Pass a 20-second MP4 fixture.')
  const input = resolve(process.argv[2])
  const originalBytes = await readFile(input)
  const source = await readFile(resolve(__dirname, '../electron/videoLibrary.ts'), 'utf8')
  const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText
  const modulePath = join(output, 'videoLibrary.cjs')
  await writeFile(modulePath, compiled)
  const { VideoLibraryStore } = require(modulePath)
  const workspace = join(output, `workspace-${randomUUID()}`)
  let library = new VideoLibraryStore(() => workspace)
  const sourceId = randomUUID(), targetId = randomUUID(), assetId = randomUUID()
  const folder = (id) => join(workspace, `studio-${id}`)
  const document = (id, title) => ({ schemaVersion: 1, id, title, color: '#b090c0', createdAt: '2026-10-17T00:00:00Z', updatedAt: '2026-10-17T00:00:00Z', backgroundColor: '#d7b5cd', backgroundAssetId: null, backgroundX: 0, backgroundY: 0, backgroundWidth: 100, backgroundHeight: 100, backgroundRotation: 0, assets: [], elements: [] })
  const oldAsset = { id: assetId, name: 'Vídeo do roteiro antigo.mp4', mimeType: 'video/mp4', extension: 'mp4', size: originalBytes.length, durationFrames: 1200 }
  await mkdir(join(folder(sourceId), 'videos'), { recursive: true })
  await mkdir(folder(targetId), { recursive: true })
  await copyFile(input, join(folder(sourceId), 'videos', `${assetId}.mp4`))
  await writeFile(join(folder(sourceId), 'studio.json'), JSON.stringify({ ...document(sourceId, 'Roteiro anterior'), videoTimeline: { videoAssets: [oldAsset] } }))
  await writeFile(join(folder(targetId), 'studio.json'), JSON.stringify(document(targetId, 'Roteiro atual')))
  ipcMain.handle('audit:list', async () => [JSON.parse(await readFile(join(folder(targetId), 'studio.json'), 'utf8'))])
  ipcMain.handle('audit:save', async (_event, value) => {
    if (value.videoTimeline?.videoAssets?.length) await library.ensureProjectAssets(targetId, value.videoTimeline.videoAssets)
    await writeFile(join(folder(targetId), 'studio.json'), JSON.stringify(value))
  })
  ipcMain.handle('audit:library:list', () => library.list())
  ipcMain.handle('audit:library:import', () => library.importFile(input))
  ipcMain.handle('audit:library:finish', (_event, id, duration) => library.finishImport(id, duration))
  ipcMain.handle('audit:library:delete', (_event, id) => library.delete(id))
  ipcMain.handle('audit:library:attach', (_event, id, ids) => library.attach(id, ids))
  const preload = join(output, 'preload.cjs')
  await writeFile(preload, `const { contextBridge, ipcRenderer } = require('electron'); contextBridge.exposeInMainWorld('desktop', {
    listVideoStudios: () => ipcRenderer.invoke('audit:list'), saveVideoStudio: (d) => ipcRenderer.invoke('audit:save', d), getVideoStudioFolder: async () => ${JSON.stringify(workspace)},
    listVideoLibrary: () => ipcRenderer.invoke('audit:library:list'), importVideoLibrary: () => ipcRenderer.invoke('audit:library:import'), finishVideoLibraryImport: (id, duration) => ipcRenderer.invoke('audit:library:finish', id, duration), deleteVideoLibraryItem: (id) => ipcRenderer.invoke('audit:library:delete', id), attachVideoLibraryItems: (id, ids) => ipcRenderer.invoke('audit:library:attach', id, ids),
    listCustomizerCharacters: async () => [], listFaceCatalog: async () => [], listFaceExpressionCollections: async () => [], listFaceExpressionPresets: async () => [], listFabricatorPoseSlots: async () => [], importVideoStudioImage: async () => null
  })`)
  await app.whenReady()
  protocol.handle('gacha-video', async (request) => {
    const url = new URL(request.url), ids = url.pathname.split('/').filter(Boolean)
    const path = url.hostname === 'library' ? (await library.resolveMedia(ids[0])).path : join(folder(ids[0]), 'videos', `${ids[1]}.mp4`)
    return new Response(await readFile(path), { headers: { 'content-type': 'video/mp4' } })
  })
  const window = new BrowserWindow({ show: false, width: 1440, height: 900, useContentSize: true, webPreferences: { preload, contextIsolation: true, sandbox: true, backgroundThrottling: false } })
  const js = (code) => window.webContents.executeJavaScript(code)
  await window.loadFile(resolve(__dirname, '../out/renderer/index.html'), { hash: '/video-studio' })
  await until(window, "Boolean(document.querySelector('.video-studio-card-open'))")
  await js("document.querySelector('.video-studio-card-open').click()")
  await until(window, "Boolean(document.querySelector('.video-add-video-button'))")
  await js("document.querySelector('.video-add-video-button').click()")
  await until(window, "document.querySelectorAll('.video-library-card').length === 1")
  assert.match(await js("document.querySelector('.video-library-origins').textContent"), /Roteiro anterior/)
  await js("document.querySelector('.video-library-select').click()")
  await until(window, "document.querySelector('.video-library-preview video')?.readyState > 1")
  await capture(window, 'library.png')
  await js("document.querySelector('.video-library-import').click()")
  await until(window, "document.querySelectorAll('.video-library-card.selected').length === 2 && !document.querySelector('.video-library-add').disabled")
  await js("document.querySelector('.video-library-add').click()")
  await until(window, "!document.querySelector('.video-library-modal') && document.querySelectorAll('.video-master-span').length === 2")
  await pause(800)
  let saved = JSON.parse(await readFile(join(folder(targetId), 'studio.json'), 'utf8'))
  assert.equal(saved.videoTimeline.videoClips.length, 2)
  assert.equal(saved.videoTimeline.videoClips[1].startFrame, 1200)
  for (const asset of saved.videoTimeline.videoAssets) await access(join(folder(targetId), 'videos', `${asset.id}.${asset.extension}`))
  await js("document.querySelector('.video-master-span').click(); document.querySelector('.video-add-video-button').click()")
  await until(window, "document.querySelectorAll('.video-library-card').length === 2")
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Backspace' })
  window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Backspace' })
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Z', modifiers: ['control'] })
  window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Z', modifiers: ['control'] })
  await js("document.querySelector('[aria-label=\"Excluir Vídeo do roteiro antigo.mp4 da biblioteca\"]').click()")
  await until(window, "document.querySelectorAll('.video-library-card').length === 1 && !document.querySelector('.video-library-close').disabled")
  await access(join(folder(targetId), 'videos', `${assetId}.mp4`))
  assert.deepEqual(await readFile(join(folder(sourceId), 'videos', `${assetId}.mp4`)), originalBytes)
  assert.equal((await library.list()).some((item) => item.id === assetId), false)
  await js("document.querySelector('.video-library-close').click()")
  await until(window, "document.querySelector('video.video-studio-video-clip-preview')?.readyState > 1")
  assert.equal((JSON.parse(await readFile(join(folder(targetId), 'studio.json'), 'utf8'))).videoTimeline.videoClips.length, 2, 'Modal shortcuts must not delete/undo scene clips')
  library = new VideoLibraryStore(() => workspace)
  window.webContents.reload()
  await until(window, "Boolean(document.querySelector('.video-studio-card-open'))")
  await js("document.querySelector('.video-studio-card-open').click()")
  await until(window, "document.querySelectorAll('.video-master-span').length === 2")
  await js("document.querySelector('.video-add-video-button').click()")
  await until(window, "document.querySelectorAll('.video-library-card').length === 1")
  saved = JSON.parse(await readFile(join(folder(targetId), 'studio.json'), 'utf8'))
  await writeFile(join(output, 'result.json'), JSON.stringify({ workspace, libraryCount: (await library.list()).length, savedClips: saved.videoTimeline.videoClips.length, sourcePreserved: true, projectCopiesPreserved: true, deletedItemStayedDeleted: true }, null, 2))
  console.log('Video library UI audit passed: legacy videos from another script, preview decoding, import, multi-selection, real file copies, deletion preserving scripts, keyboard isolation, disk save, and reload.')
  window.destroy(); app.exit(0)
}
run().catch((error) => { console.error(error); app.exit(1) })
