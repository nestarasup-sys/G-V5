import assert from 'node:assert/strict'
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { resolve, join } from 'node:path'
import { randomUUID } from 'node:crypto'
import ts from 'typescript'

const source = await readFile(new URL('../electron/videoLibrary.ts', import.meta.url), 'utf8')
const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText
const { VideoLibraryStore } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`)
const root = resolve('out/audit-video-library', randomUUID())
await mkdir(root, { recursive: true })
const bytes = Buffer.from('immutable-video-fixture')
const firstId = randomUUID(), secondId = randomUUID(), thirdId = randomUUID(), fourthId = randomUUID(), assetId = randomUUID()
const asset = { id: assetId, name: 'Vídeo antigo.mp4', extension: 'mp4', mimeType: 'video/mp4', size: bytes.length, durationFrames: 1200 }
const projectPath = (id) => join(root, `studio-${id}`)
const mediaPath = (id) => join(projectPath(id), 'videos', `${assetId}.mp4`)
async function manifest(id, assets) {
  await mkdir(projectPath(id), { recursive: true })
  await writeFile(join(projectPath(id), 'studio.json'), JSON.stringify({ id, title: `Roteiro ${id}`, createdAt: '2026-10-17T00:00:00Z', videoTimeline: { videoAssets: assets } }))
}
await manifest(firstId, [asset])
await mkdir(join(projectPath(firstId), 'videos'), { recursive: true })
await writeFile(mediaPath(firstId), bytes)
const library = new VideoLibraryStore(() => root)
const migrated = await library.list()
assert.equal(migrated.length, 1)
assert.equal(migrated[0].id, assetId)
assert.equal(migrated[0].studios[0].id, firstId)
const copy = await library.attach(secondId, [assetId, assetId])
assert.equal(copy.length, 1, 'Selecting an asset twice must not create two copies')
await manifest(secondId, copy)
assert.deepEqual(await readFile(mediaPath(secondId)), bytes)
assert.deepEqual(await readFile(mediaPath(firstId)), bytes)
assert.equal((await readdir(join(projectPath(secondId), 'videos'))).length, 1)
await writeFile(mediaPath(secondId), Buffer.from('conflicting-file'))
await assert.rejects(library.attach(secondId, [assetId]), /tamanho inesperado/)
assert.equal((await readFile(mediaPath(secondId))).toString(), 'conflicting-file', 'A conflicting destination must not be overwritten')
await writeFile(mediaPath(secondId), bytes)
assert.equal((await library.list())[0].studios.length, 2)
await library.ensureProjectAssets(thirdId, [asset])
assert.deepEqual(await readFile(mediaPath(thirdId)), bytes, 'Duplicated scripts must receive their own video file')
await library.delete(assetId)
await assert.rejects(library.resolveMedia(assetId), /não encontrado/)
assert.equal((await library.list()).length, 0, 'Deleted entries must not return from legacy projects')
assert.deepEqual(await readFile(mediaPath(firstId)), bytes)
assert.deepEqual(await readFile(mediaPath(secondId)), bytes)
await library.ensureProjectAssets(fourthId, [asset])
assert.deepEqual(await readFile(mediaPath(fourthId)), bytes, 'A deleted catalog entry must not break copying an existing script')
assert.equal((await new VideoLibraryStore(() => root).list()).length, 0, 'Deletion tombstones must survive restart')
const input = join(root, 'upload.mp4')
await writeFile(input, bytes)
const imported = await library.importFile(input)
assert.equal(imported.durationFrames, null)
assert.equal((await new VideoLibraryStore(() => root).list())[0].id, imported.id, 'An import must persist before metadata decoding')
await assert.rejects(library.attach(secondId, [imported.id]), /duração/)
await library.finishImport(imported.id, 600)
const added = await library.attach(secondId, [imported.id])
assert.equal(added[0].durationFrames, 600)
assert.deepEqual(await readFile(join(projectPath(secondId), 'videos', `${imported.id}.mp4`)), bytes)
await assert.rejects(library.delete('../escape'), /inválido/)
await assert.rejects(library.attach('../escape', [imported.id]), /inválido/)
await assert.rejects(library.finishImport(imported.id, Infinity), /inválida/)
assert.deepEqual(await readFile(input), bytes, 'Importing must not move or change the source')
const result = await new VideoLibraryStore(() => root).list()
assert.equal(result[0].durationFrames, 600)
console.log('Video library audit passed: legacy migration, independent copies, deduplication by asset ID, deletion/restart, pending imports, source preservation, and path validation.')
